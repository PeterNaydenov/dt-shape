/**
 * Creates CommonJS type definitions (types/main.d.cts) from types/main.d.ts.
 *
 * The CommonJS and UMD builds export the dtShape function as 'module.exports', so the types use 'export ='.
 * Exported types of main.d.ts are moved inside the 'dtShape' namespace, so CommonJS consumers
 * can use them as 'dtShape.Shape', 'dtShape.DTObject', etc. References to them get the 'dtShape.' prefix.
 */
import fs from 'node:fs'

const
      source = 'types/main.d.ts'
    , target = 'types/main.d.cts'
    , imports = /^import type [^\n]*;\n/gm
    , typeDeclarations = /^export type (?:[^\n]*;|[^\n]*\{\n[\s\S]*?^\};)\n/gm
    , namespaceDeclaration = /^declare namespace dtShape \{\n([\s\S]*?)^\}\n/m
    , defaultExport = /^export default dtShape;\s*$/m
    ;

const esm = fs.readFileSync ( source, 'utf8' );
if ( !namespaceDeclaration.test ( esm ) || !defaultExport.test ( esm ) ) {
        throw new Error ( `build-cts-types: Unexpected content in ${source}. Update the script.` )
    }

const
      importLines = esm.match ( imports ) || []
    , types = esm.match ( typeDeclarations ) || []
    , typeNames = types.map ( t => t.match ( /^export type (\w+)/ )[1] )
    , typeReference = new RegExp ( `(?<![\\w.])(${typeNames.join ( '|' )})\\b(?!\\s*=)`, 'g' )
    , isComment = line => /^\s*(\/\*\*|\*)/.test ( line )
    , indent = text => text.split ( '\n' ).map ( line => line ? `    ${line}` : line ).join ( '\n' )
    ;

let body = esm
            .replace ( imports, '' )
            .replace ( typeDeclarations, '' )
            .split ( '\n' )
            .map ( line => isComment ( line ) ? line : line.replace ( typeReference, 'dtShape.$1' ) )   // Types are moved inside the namespace
            .join ( '\n' )
            .replace ( namespaceDeclaration, ( _, members ) => `declare namespace dtShape {\n${indent ( types.join ('') )}${members}}\n` )
            .replace ( defaultExport, 'export = dtShape;\nexport as namespace dtShape;\n' )
            ;

if ( /^export (?!=|as namespace)/m.test ( body ) ) {
        throw new Error ( `build-cts-types: ${source} contains exports that are not supported. Update the script.` )
    }

const cjs = `// Generated by scripts/build-cts-types.js from main.d.ts. Do not edit.
${importLines.join ( '' )}${body}`;

fs.writeFileSync ( target, cjs )


